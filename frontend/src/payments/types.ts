// What the payments API answers (backend/app/payments). Amounts are integers of minor units.

export type Cap = { available: boolean; reason: string | null };
export type Account = {
  provider: "stripe" | "fake";
  account_id: string;
  status: "pending" | "active" | "restricted" | "disconnected";
  charges_enabled: boolean;
  payouts_enabled: boolean;
  details_submitted: boolean;
  livemode: boolean;
  display_name: string | null;
};
export type AccountView = {
  account: Account | null;
  capabilities: Record<"invoices" | "manual_payments" | "online_payments" | "payment_links" | "subscriptions" | "saved_cards" | "refunds", Cap>;
  providers: { key: "stripe" | "fake"; label: string; available: boolean; reason: string | null }[];
  webhook_path: string;
  url?: string | null;
};
export type Settings = {
  default_currency: string;
  invoice_prefix: string;
  invoice_due_days: number;
  retry_days: number[];
  after_retries: "cancel" | "unpaid";
  business_name: string;
  business_details: string;
  invoice_footer: string;
  next_invoice_number: number;
};
export type TaxRate = { id: string; name: string; percentage_bp: number; inclusive: boolean; region: string; active: boolean };
export type Tier = { up_to: number | null; unit_amount: number; flat_amount: number };
export type Price = {
  id: string;
  product_id: string;
  product_name?: string;
  nickname: string;
  currency: string;
  type: "one_time" | "recurring";
  scheme: "fixed" | "tiered";
  unit_amount: number | null;
  tiers: Tier[];
  tiers_mode: "graduated" | "volume" | null;
  interval: "day" | "week" | "month" | "year" | null;
  interval_count: number;
  trial_days: number;
  tax_rate_id: string | null;
  active: boolean;
};
export type Product = { id: string; name: string; description: string; kind: "service" | "physical" | "digital"; active: boolean; prices: Price[]; created_at: string };
export type Coupon = {
  id: string;
  name: string;
  code: string;
  percent_off_bp: number | null;
  amount_off: number | null;
  currency: string | null;
  duration: "once" | "repeating" | "forever";
  duration_months: number | null;
  max_redemptions: number | null;
  times_redeemed: number;
  once_per_contact: boolean;
  expires_at: string | null;
  active: boolean;
};
export type ContactRef = { id: string; display_name: string } | null;
export type InvoiceStatus = "draft" | "open" | "paid" | "void" | "uncollectible";
export type Line = {
  id: string;
  description: string;
  price_id: string | null;
  quantity: number;
  unit_amount: number;
  amount: number;
  discount: number;
  tax_rate_id: string | null;
  tax_name: string;
  tax_bp: number;
  tax_inclusive: boolean;
  tax: number;
  total: number;
  proration: boolean;
};
export type Invoice = {
  id: string;
  number: string | null;
  status: InvoiceStatus;
  billing_reason: string;
  contact: ContactRef;
  contact_id: string | null;
  currency: string;
  subscription_id: string | null;
  coupon_id: string | null;
  subtotal: number;
  discount: number;
  tax: number;
  credit_applied: number;
  total: number;
  amount_paid: number;
  amount_due: number;
  due_at: string | null;
  issued_at: string | null;
  paid_at: string | null;
  memo: string;
  footer: string;
  attempt_count: number;
  next_attempt_at: string | null;
  public_url: string | null;
  created_at: string;
  lines?: Line[];
  payments?: { id: string; amount: number; status: string; provider: string; method: string; amount_refunded: number; created_at: string }[];
};
export type SubStatus = "incomplete" | "incomplete_expired" | "trialing" | "active" | "past_due" | "unpaid" | "canceled";
export type Subscription = {
  id: string;
  contact: ContactRef;
  price: Price | null;
  price_id: string;
  product_name: string | null;
  quantity: number;
  currency: string;
  status: SubStatus;
  collection: "charge_automatically" | "send_invoice";
  cancel_at_period_end: boolean;
  canceled_at: string | null;
  trial_end: string | null;
  current_period_start: string | null;
  current_period_end: string | null;
  credit_balance: number;
  amount: number | null;
  card: { brand: string | null; last4: string | null } | null;
  latest_invoice_id: string | null;
  created_at: string;
  invoices?: Invoice[];
};
export type Refund = { id: string; amount: number; reason: string | null; note: string; status: "pending" | "succeeded" | "failed"; failure_message: string | null; created_at: string };
export type Payment = {
  id: string;
  contact: ContactRef;
  invoice_id: string | null;
  invoice_number: string | null;
  subscription_id: string | null;
  provider: "stripe" | "fake" | "manual";
  amount: number;
  currency: string;
  status: "pending" | "processing" | "succeeded" | "failed" | "canceled";
  amount_refunded: number;
  refundable: number | null;
  method: string;
  note: string;
  failure_code: string | null;
  failure_message: string | null;
  created_at: string;
  refunds?: Refund[];
};
export type LinkItem = { price_id: string; quantity: number; adjustable: boolean; min: number; max: number };
export type PaymentLink = { id: string; name: string; active: boolean; items: LinkItem[]; allow_coupons: boolean; collect_phone: boolean; success_message: string; redirect_url: string | null; public_url: string; created_at: string };
export type Summary = { currencies: { currency: string; net_volume: number; gross_volume: number; refunded: number; outstanding: number; mrr: number }[]; live_subscriptions: number; saved_cards: number };
export type Page<T> = { data: T[]; next_cursor: string | null };
